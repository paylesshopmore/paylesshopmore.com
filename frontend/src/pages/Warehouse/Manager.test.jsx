describe('who gets in', () => {
  it('sends a warehouse worker back to the warehouse home', async () => {
    auth.user = { id: 7, role: 'warehouse', isWarehouse: true };
    renderAt('/warehouse/manager');

    expect(await screen.findByText('Warehouse home')).toBeInTheDocument();
    expect(getManagerStats).not.toHaveBeenCalled();
  });

  it('lets an admin in', async () => {
    auth.user = { id: 1, role: 'admin', isAdmin: true, isStaff: true };
    renderAt('/warehouse/manager');
    expect(await screen.findByRole('heading', { name: 'Warehouse management' })).toBeInTheDocument();
  });

  it('shows the three tabs', async () => {
    renderAt('/warehouse/manager');
    const tabs = await screen.findByRole('navigation', { name: 'Warehouse management sections' });
    expect(within(tabs).getAllByRole('link').map((link) => link.textContent)).toEqual([
      'Overview',
      'Workers',
      'Activity log',
    ]);
  });
});

describe('the overview', () => {
  it('shows every number', async () => {
    renderAt('/warehouse/manager');

    const cards = await screen.findAllByRole('listitem');
    const text = cards.map((card) => card.textContent).join('|');
    expect(text).toContain('Active workers6');
    expect(text).toContain('Signed in now2');
    expect(text).toContain('Received today14');
    expect(text).toContain('Ready to ship today9');
    expect(text).toContain('Waiting for processing31');
    expect(text).toContain('Without a customer0');
    expect(text).toContain('Not measured yet12');
    expect(text).toContain('Problems and damage3');
  });

  it('names who is signed in, and today per worker', async () => {
    renderAt('/warehouse/manager');

    expect(await screen.findByText('Wim Tromp, Ana Silva')).toBeInTheDocument();
    const today = screen.getByRole('region', { name: 'Today per worker' });
    expect(within(today).getByRole('columnheader', { name: 'Scanned' })).toBeInTheDocument();
    expect(within(today).getByRole('rowheader', { name: 'Total' })).toBeInTheDocument();
  });

  it('links each package that needs attention to its own page', async () => {
    renderAt('/warehouse/manager');

    const attention = await screen.findByRole('region', { name: 'Needs attention' });
    expect(within(attention).getByRole('link', { name: /PLS-41/ })).toHaveAttribute(
      'href',
      '/warehouse/packages/41',
    );
    expect(within(attention).getByRole('link', { name: /PLS-42/ })).toHaveAttribute(
      'href',
      '/warehouse/packages/42',
    );
    // 12 missing, 1 listed: says it is showing the first of more.
    expect(within(attention).getByText('Showing the first 1 of 12.')).toBeInTheDocument();
    // An empty list says so rather than showing nothing.
    expect(within(attention).getAllByText('Nothing here.').length).toBeGreaterThan(0);
  });

  it('can be refreshed', async () => {
    const user = userEvent.setup();
    renderAt('/warehouse/manager');
    await screen.findByText('Wim Tromp, Ana Silva');

    await user.click(screen.getByRole('button', { name: 'Refresh' }));
    await waitFor(() => expect(getManagerStats).toHaveBeenCalledTimes(2));
  });

  it('offers to try again when the numbers cannot be loaded', async () => {
    getManagerStats.mockRejectedValue(new Error('offline'));
    renderAt('/warehouse/manager');
    expect(await screen.findByRole('button', { name: /try again/i })).toBeInTheDocument();
  });
});

describe('the activity log', () => {
  it('lists who did what, to which package, with what changed', async () => {
    renderAt('/warehouse/manager/activity');

    const rows = await screen.findAllByRole('row');
    const measurement = rows.find((row) => row.textContent.includes('PLS-42'));
    expect(measurement).toHaveTextContent('Ana Silva');
    expect(measurement).toHaveTextContent('Measurement changed');
    // Only what actually changed: the weight, not the length.
    expect(measurement).toHaveTextContent('Weight (kg): 12.50 → 13.00');
    expect(measurement).not.toHaveTextContent('Length (cm)');
    expect(within(measurement).getByRole('link', { name: 'PLS-42' })).toHaveAttribute(
      'href',
      '/warehouse/packages/42',
    );

    const issued = rows.find((row) => row.textContent.includes('Mila Chef'));
    expect(issued).toHaveTextContent('PIN generated');
    expect(issued).toHaveTextContent('for Wim Tromp');
  });

  it('asks for the filter options once, with the first page', async () => {
    renderAt('/warehouse/manager/activity');
    await screen.findAllByRole('row');
    expect(getManagerActivity).toHaveBeenCalledWith(expect.objectContaining({ options: true, page: 1 }));
    expect(screen.getByRole('option', { name: /Old Hand \(switched off\)/ })).toBeInTheDocument();
  });

  it('filters by worker, keeps it in the address, and starts on page 1', async () => {
    const user = userEvent.setup();
    renderAt('/warehouse/manager/activity?page=3');
    await screen.findAllByRole('row');

    await user.selectOptions(screen.getByLabelText('Worker'), '7');

    await waitFor(() =>
      expect(getManagerActivity).toHaveBeenLastCalledWith(
        expect.objectContaining({ worker: '7', page: 1, options: false }),
      ),
    );
    expect(screen.getByTestId('where')).toHaveTextContent('/warehouse/manager/activity?worker=7');
  });

  it('filters by tracking number on Enter', async () => {
    const user = userEvent.setup();
    renderAt('/warehouse/manager/activity');
    await screen.findAllByRole('row');

    await user.type(screen.getByLabelText('Tracking number'), 'PLS-42{Enter}');

    await waitFor(() =>
      expect(getManagerActivity).toHaveBeenLastCalledWith(expect.objectContaining({ tracking: 'PLS-42' })),
    );
  });

  it('clears every filter at once', async () => {
    const user = userEvent.setup();
    renderAt('/warehouse/manager/activity?worker=7&action=pin_issued');
    await screen.findAllByRole('row');

    await user.click(screen.getByRole('button', { name: 'Clear filters' }));

    expect(screen.getByTestId('where')).toHaveTextContent(/^\/warehouse\/manager\/activity$/);
  });

  it('says so when nothing matches', async () => {
    getManagerActivity.mockResolvedValue({ ...ACTIVITY, count: 0, results: [] });
    renderAt('/warehouse/manager/activity?action=wrong_pin');
    expect(await screen.findByText('Nothing matches these filters.')).toBeInTheDocument();
  });

  it('pages through', async () => {
    const user = userEvent.setup();
    getManagerActivity.mockResolvedValue({ ...ACTIVITY, count: 120, has_next: true });
    renderAt('/warehouse/manager/activity');
    await screen.findAllByRole('row');

    await user.click(screen.getByRole('button', { name: /next/i }));

    await waitFor(() =>
      expect(getManagerActivity).toHaveBeenLastCalledWith(expect.objectContaining({ page: 2 })),
    );
  });
});
